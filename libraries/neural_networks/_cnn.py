"""A from-scratch NumPy CNN, following the course student guide.

All image data is NHWC: ``(batch_size, height, width, channels)``.

Layers implement ``__call__`` (forward), ``backward`` (returns the gradient
w.r.t. their input) and, when they hold parameters, ``update``.
``CNNClassifier`` chains feature layers with a flatten step, a
``ModularLinearLayer`` and a ``SoftmaxLayer``, trained with mini-batch
gradient descent on the cross-entropy loss.
"""

from __future__ import annotations

from typing import List, Optional, Sequence, Tuple, Union

import numpy as np

__all__ = [
    "get_patches",
    "pad_images",
    "ConvLayer",
    "PoolingLayer",
    "ReLULayer",
    "SoftmaxLayer",
    "ModularLinearLayer",
    "CNNClassifier",
]

SizeLike = Union[int, Tuple[int, int]]


