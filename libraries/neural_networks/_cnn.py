class PoolingLayer:
    """Max-pooling layer: shrinks each feature map by keeping the largest value per window."""

    def __init__(self, pool_size: SizeLike = 2, stride: SizeLike = 2, padding: int = 0):
        """Create a max-pooling layer with the given window size and stride."""
        self.pool_size = _as_pair(pool_size, "pool_size")
        self.stride = _as_pair(stride, "stride")
        self.padding = int(padding)
        # alias used by the course evaluator
        self.kernel_size = self.pool_size
        self._prev_input: Optional[np.ndarray] = None
        self._previous_input: Optional[np.ndarray] = None

    def __call__(self, X: np.ndarray) -> np.ndarray:
        """Forward pass: apply max pooling.

        Args:
            X: ndarray of shape (batch_size, height, width, channels)

        Returns:
            ndarray of shape (batch_size, out_height, out_width, channels)
        """
        if X.ndim != 4:
            raise ValueError(f"expected (B, H, W, C) input, got shape {X.shape}")
        X = pad_images(X, self.padding)
        self._prev_input = X
        self._previous_input = X
        patches = get_patches(X, self.pool_size, self.stride)
        return np.max(patches, axis=(-2, -1))

    def backward(self, grad_output: np.ndarray) -> np.ndarray:
        """Route gradients back through max positions."""
        if self._prev_input is None:
            raise RuntimeError("run the forward pass before calling backward()")
        X = self._prev_input
        pH, pW = self.pool_size
        sH, sW = self.stride

        patches = get_patches(X, self.pool_size, self.stride)
        b, out_h, out_w, c = grad_output.shape
        flat = patches.reshape(b, out_h, out_w, c, pH * pW)
        winner = np.argmax(flat, axis=-1)
        win_h, win_w = winner // pW, winner % pW

        bi, oy, ox, ci = np.indices((b, out_h, out_w, c), sparse=False)
        grad_input = np.zeros_like(X)
        # add.at accumulates when windows overlap (stride < pool size)
        np.add.at(
            grad_input,
            (bi, oy * sH + win_h, ox * sW + win_w, ci),
            grad_output,
        )
        if self.padding:
            p = self.padding
            grad_input = grad_input[:, p : grad_input.shape[1] - p, p : grad_input.shape[2] - p, :]
        return grad_input

    def get_output_shape(self, input_shape: Tuple[int, int, int]) -> Tuple[int, int, int]:
        """Output (height, width, channels) for an input (height, width, channels)."""
        h, w = input_shape[0] + 2 * self.padding, input_shape[1] + 2 * self.padding
        out_h = (h - self.pool_size[0]) // self.stride[0] + 1
        out_w = (w - self.pool_size[1]) // self.stride[1] + 1
        return (out_h, out_w, input_shape[2])

    def __repr__(self) -> str:
        """Readable description of the layer configuration."""
        return f"PoolingLayer(pool_size={self.pool_size}, stride={self.stride})"


