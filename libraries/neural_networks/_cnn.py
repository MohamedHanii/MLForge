class ModularLinearLayer:
    """Fully connected layer computing ``X @ weight + bias`` for classification heads."""

    def __init__(
        self,
        input_size: int,
        output_size: int,
        rng: Optional[np.random.RandomState] = None,
    ):
        """Create the layer: Xavier-uniform weights, zero biases."""
        self.input_size = int(input_size)
        self.output_size = int(output_size)
        # aliases used by the course evaluator
        self.in_features = self.input_size
        self.out_features = self.output_size

        rng = rng if rng is not None else np.random.RandomState()
        limit = np.sqrt(6.0 / (self.input_size + self.output_size))
        self.weight = rng.uniform(-limit, limit, (self.input_size, self.output_size))
        self.bias = np.zeros(self.output_size)
        self.weight_ = self.weight
        self.bias_ = self.bias

        self._weight_grad: Optional[np.ndarray] = None
        self._bias_grad: Optional[np.ndarray] = None
        self._prev_input: Optional[np.ndarray] = None
        self._weight_velocity: Optional[np.ndarray] = None
        self._bias_velocity: Optional[np.ndarray] = None

    def __call__(self, X: np.ndarray) -> np.ndarray:
        """Forward pass: X @ weight + bias."""
        if X.ndim != 2 or X.shape[1] != self.input_size:
            raise ValueError(
                f"expected input of shape (batch, {self.input_size}), got {X.shape}"
            )
        self._prev_input = X
        return X.dot(self.weight) + self.bias

    def backward(
        self, grad_output: np.ndarray, alpha: Optional[float] = None
    ) -> np.ndarray:
        """Compute gradients w.r.t. input, weights, and biases.

        ``alpha`` adds an L2 penalty gradient (``alpha * weight``) to the
        weight gradient.
        """
        if self._prev_input is None:
            raise RuntimeError("run the forward pass before calling backward()")
        self._weight_grad = self._prev_input.T.dot(grad_output)
        if alpha:
            self._weight_grad = self._weight_grad + alpha * self.weight
        self._bias_grad = np.sum(grad_output, axis=0)
        return grad_output.dot(self.weight.T)

    def update(self, learning_rate: float, momentum: float = 0.0) -> None:
        """Update weights and biases (gradient descent, optionally with momentum)."""
        if self._weight_grad is None:
            raise RuntimeError("call backward() before update()")
        if momentum:
            if self._weight_velocity is None:
                self._weight_velocity = np.zeros_like(self.weight)
                self._bias_velocity = np.zeros_like(self.bias)
            self._weight_velocity = (
                momentum * self._weight_velocity - learning_rate * self._weight_grad
            )
            self._bias_velocity = (
                momentum * self._bias_velocity - learning_rate * self._bias_grad
            )
            self.weight += self._weight_velocity
            self.bias += self._bias_velocity
        else:
            self.weight -= learning_rate * self._weight_grad
            self.bias -= learning_rate * self._bias_grad

    def __repr__(self) -> str:
        """Readable description of the layer configuration."""
        return f"ModularLinearLayer({self.input_size}, {self.output_size})"


