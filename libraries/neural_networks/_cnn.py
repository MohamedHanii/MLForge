class ReLULayer:
    """ReLU activation layer: f(x) = max(0, x)."""

    def __init__(self):
        """Create the activation layer (no parameters)."""
        self._mask: Optional[np.ndarray] = None
        self._prev_result: Optional[np.ndarray] = None

    def __call__(self, X: np.ndarray) -> np.ndarray:
        """Forward pass: zero out negative values, keep positive ones."""
        self._mask = X > 0
        self._prev_result = np.maximum(0.0, X)
        return self._prev_result

    def backward(self, grad_output: np.ndarray) -> np.ndarray:
        """Backward pass: let gradients through only where the input was positive."""
        if self._mask is None:
            raise RuntimeError("run the forward pass before calling backward()")
        return grad_output * self._mask

    def __repr__(self) -> str:
        """Readable description of the layer."""
        return "ReLULayer()"


class SoftmaxLayer:
    """Softmax activation layer: maps class scores to probabilities that sum to 1."""

    def __init__(self):
        """Create the activation layer (no parameters)."""
        self._prev_result: Optional[np.ndarray] = None

    def __call__(self, X: np.ndarray) -> np.ndarray:
        """Forward pass: turn each row of scores into a probability distribution."""
        # subtracting the row max keeps exp() from overflowing
        shifted = X - np.max(X, axis=-1, keepdims=True)
        exp = np.exp(shifted)
        self._prev_result = exp / np.sum(exp, axis=-1, keepdims=True)
        return self._prev_result

    def backward(self, grad_output: np.ndarray) -> np.ndarray:
        """Backward pass: gradient through the softmax function."""
        # full Jacobian-vector product: p * (g - sum(g * p))
        if self._prev_result is None:
            raise RuntimeError("run the forward pass before calling backward()")
        p = self._prev_result
        return p * (grad_output - np.sum(grad_output * p, axis=-1, keepdims=True))

    def __repr__(self) -> str:
        """Readable description of the layer."""
        return "SoftmaxLayer()"


