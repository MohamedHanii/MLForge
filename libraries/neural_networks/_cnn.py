class CNNClassifier:
    """Convolutional Neural Network for image classification.

    Chains the feature layers, flattens their output, and adds a linear +
    softmax head. Trained with mini-batch SGD (momentum, optional learning-rate
    decay and early stopping) on the cross-entropy loss.
    """

    def __init__(
        self,
        input_shape: Tuple[int, int, int] = (28, 28, 1),
        num_classes: int = 10,
        lr: float = 0.01,
        epochs: int = 20,
        batch_size: int = 32,
        random_state: Optional[int] = None,
        layers: Optional[Sequence] = None,
        alpha: float = 0.0,
        verbose: bool = True,
        momentum: float = 0.9,
        lr_decay: float = 0.0,
        early_stopping: bool = True,
        tol: float = 1e-4,
        n_iter_no_change: int = 5,
        max_grad_norm: Optional[float] = None,
    ):
        # Generated By LLM 
        """Store and validate the hyperparameters (nothing is trained yet)."""
        if lr <= 0:
            raise ValueError(f"lr must be positive, got {lr}")
        if int(epochs) <= 0:
            raise ValueError(f"epochs must be positive, got {epochs}")
        if int(batch_size) <= 0:
            raise ValueError(f"batch_size must be positive, got {batch_size}")
        if alpha < 0:
            raise ValueError(f"alpha must be non-negative, got {alpha}")
        if not 0.0 <= momentum < 1.0:
            raise ValueError(f"momentum must be in [0, 1), got {momentum}")
        if lr_decay < 0:
            raise ValueError(f"lr_decay must be non-negative, got {lr_decay}")

        self.input_shape = tuple(input_shape)
        self.num_classes = int(num_classes)
        self.lr = lr
        self.epochs = int(epochs)
        self.batch_size = int(batch_size)
        self.random_state = random_state
        self.alpha = alpha
        self.verbose = verbose
        self.momentum = momentum
        self.lr_decay = lr_decay
        self.early_stopping = early_stopping
        self.tol = tol
        self.n_iter_no_change = int(n_iter_no_change)
        self.max_grad_norm = max_grad_norm
        # list of layer objects (set during build/fit)
        self.layers_: List = list(layers) if layers is not None else []
        self._given_layers = layers

    # -- architecture ------------------------------------------------------

    def _build_layers(self) -> List:
        """Default feature-extraction stack when no layers were given.

        Pooling halves the spatial size, so it is only added while the
        feature map stays at least 4x4 - small inputs (e.g. 8x8 digits)
        would otherwise be crushed to almost nothing.
        """
        h, w, channels = self.input_shape
        layers: List = [
            ConvLayer(channels, 8, 3, padding="same", rng=self.rng_),
            ReLULayer(),
        ]
        if min(h, w) >= 8:
            layers.append(PoolingLayer(2, 2))
            h, w = h // 2, w // 2
        layers += [
            ConvLayer(8, 16, 3, padding="same", rng=self.rng_),
            ReLULayer(),
        ]
        if min(h, w) >= 8:
            layers.append(PoolingLayer(2, 2))
        return layers

    def _feature_shape(self) -> Tuple[int, int, int]:
        """Shape (h, w, c) coming out of the last feature layer."""
        shape = self.input_shape
        for layer in self.layers_:
            if hasattr(layer, "get_output_shape"):
                shape = layer.get_output_shape(shape)
        if shape[0] <= 0 or shape[1] <= 0:
            raise ValueError(
                f"layer stack reduces {self.input_shape} to empty output {shape}"
            )
        return shape

    # -- forward / loss ----------------------------------------------------

    def _forward(self, X: np.ndarray) -> np.ndarray:
        """Forward pass through all layers; returns class probabilities."""
        res = X
        for layer in self.layers_:
            res = layer(res)
        self._feat_shape_ = res.shape[1:]
        res = res.reshape(len(res), -1)
        res = self.out_layer_(res)
        return self.softmax_layer_(res)

    def _calculate_loss(
        self, logits: np.ndarray, y: np.ndarray
    ) -> Tuple[float, np.ndarray]:
        """Cross-entropy loss (+ L2 penalty) and its gradient w.r.t. the probabilities.

        Args:
            logits: predicted class probabilities, shape (batch, num_classes)
            y: one-hot targets of the same shape
        """
        batch = len(y)
        probs = np.clip(logits, 1e-12, None)
        loss = float(-np.sum(y * np.log(probs)) / batch)
        if self.alpha:
            l2 = sum(
                float(np.sum(layer.weight ** 2))
                for layer in [*self.layers_, self.out_layer_]
                if hasattr(layer, "weight")
            )
            loss += 0.5 * self.alpha * l2
        grad = -(y / probs) / batch
        return loss, grad

    def _backward(self, grad: np.ndarray) -> None:
        """Propagate the loss gradient back through every layer."""
        grad = self.softmax_layer_.backward(grad)
        grad = self.out_layer_.backward(grad, self.alpha)
        grad = grad.reshape(len(grad), *self._feat_shape_)
        for layer in reversed(self.layers_):
            if hasattr(layer, "update"):
                grad = layer.backward(grad, self.alpha)
            else:
                grad = layer.backward(grad)

    # Generated By LLM 
    def _clip_gradients(self) -> None:
        """Scale all parameter gradients so their global L2 norm <= max_grad_norm."""
        if self.max_grad_norm is None:
            return
        param_layers = [l for l in [*self.layers_, self.out_layer_] if hasattr(l, "update")]
        total = np.sqrt(
            sum(
                float(np.sum(l._weight_grad ** 2)) + float(np.sum(l._bias_grad ** 2))
                for l in param_layers
            )
        )
        if total > self.max_grad_norm:
            scale = self.max_grad_norm / (total + 1e-12)
            for l in param_layers:
                l._weight_grad = l._weight_grad * scale
                l._bias_grad = l._bias_grad * scale

    def _update(self, learning_rate: float) -> None:
        """Apply one gradient-descent step to every layer with parameters."""
        for layer in self.layers_:
            if hasattr(layer, "update"):
                layer.update(learning_rate, self.momentum)
        self.out_layer_.update(learning_rate, self.momentum)

    def _validate_images(self, X) -> np.ndarray:
        """Cast to a float64 NHWC batch, tolerating a missing single-channel dim."""
        X = np.asarray(X, dtype=float)
        if X.ndim == 3 and self.input_shape[2] == 1:
            X = X[..., None]
        if X.ndim != 4:
            raise ValueError(f"expected (n, H, W, C) input, got shape {X.shape}")
        return X

    # -- public API --------------------------------------------------------

    def fit(self, X: np.ndarray, y: np.ndarray) -> "CNNClassifier":
        """Train the CNN.

        Args:
            X: ndarray of shape (n_samples, height, width, channels)
            y: ndarray of shape (n_samples,) with integer class labels
        """
        X = self._validate_images(X)
        y = np.asarray(y).ravel()
        
        # Generated By LLM 
        if len(X) == 0:
            raise ValueError("cannot fit on an empty dataset")
        if len(y) != len(X):
            raise ValueError(f"X has {len(X)} samples but y has {len(y)} labels")
        if X.shape[1:] != tuple(self.input_shape):
            raise ValueError(
                f"input shape {X.shape[1:]} does not match input_shape={self.input_shape}"
            )
        if not np.isfinite(X).all():
            raise ValueError("X contains NaN or infinite values")
        if not np.issubdtype(y.dtype, np.integer):
            if not np.all(np.mod(y, 1) == 0):
                raise ValueError("y must contain integer class labels")
            y = y.astype(int)
        if (y < 0).any():
            raise ValueError("class labels must be non-negative integers")

        self.rng_ = np.random.RandomState(self.random_state)
        self.layers_ = (
            list(self._given_layers)
            if self._given_layers is not None
            else self._build_layers()
        )
        n_classes = max(self.num_classes, int(y.max()) + 1)
        feat_h, feat_w, feat_c = self._feature_shape()
        self.out_layer_ = ModularLinearLayer(
            feat_h * feat_w * feat_c, n_classes, rng=self.rng_
        )
        self.softmax_layer_ = SoftmaxLayer()

        onehot = np.zeros((len(y), n_classes))
        onehot[np.arange(len(y)), y] = 1.0

        best_loss = np.inf
        stagnant_epochs = 0
        for epoch in range(self.epochs):
            # inverse-time learning-rate decay (constant when lr_decay=0)
            learning_rate = self.lr / (1.0 + self.lr_decay * epoch)
            order = self.rng_.permutation(len(X))
            losses = []
            for start in range(0, len(X), self.batch_size):
                batch = order[start : start + self.batch_size]
                probs = self._forward(X[batch])
                loss, grad = self._calculate_loss(probs, onehot[batch])
                losses.append(loss)
                self._backward(grad)
                self._clip_gradients()
                self._update(learning_rate)
            epoch_loss = float(np.mean(losses))
            if self.verbose:
                print(f"Epoch {epoch} Loss {epoch_loss:.4f}")
            if epoch_loss < best_loss - self.tol:
                best_loss = epoch_loss
                stagnant_epochs = 0
            else:
                stagnant_epochs += 1
                if self.early_stopping and stagnant_epochs >= self.n_iter_no_change:
                    if self.verbose:
                        print(
                            f"Early stopping at epoch {epoch}: loss has not improved "
                            f"by more than {self.tol} for {self.n_iter_no_change} epochs"
                        )
                    break
        return self

    def predict(self, X: np.ndarray) -> np.ndarray:
        """Predict class labels.

        Args:
            X: ndarray of shape (n_samples, height, width, channels)

        Returns:
            ndarray of shape (n_samples,) with predicted class labels
        """
        if not hasattr(self, "out_layer_"):
            raise RuntimeError("this CNNClassifier is not fitted yet; call fit() first")
        X = self._validate_images(X)
        preds = []
        # chunked evaluation keeps the patch views from ballooning memory
        chunk = max(self.batch_size, 64)
        for start in range(0, len(X), chunk):
            probs = self._forward(X[start : start + chunk])
            preds.append(np.argmax(probs, axis=1))
        return np.concatenate(preds)

    def score(self, X: np.ndarray, y: np.ndarray) -> float:
        """Mean accuracy on the given data."""
        return float(np.mean(self.predict(X) == np.asarray(y)))

    def __repr__(self) -> str:
        """Readable description of the classifier configuration."""
        return (
            f"CNNClassifier(input_shape={self.input_shape}, "
            f"num_classes={self.num_classes}, lr={self.lr}, epochs={self.epochs}, "
            f"batch_size={self.batch_size}, alpha={self.alpha})"
        )
