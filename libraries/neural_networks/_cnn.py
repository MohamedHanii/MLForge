class ConvLayer:
    """2D convolutional layer: slides learnable filters over the image to extract features."""

    def __init__(
        self,
        in_channels: int,
        out_channels: int,
        kernel_size: SizeLike,
        stride: SizeLike = 1,
        padding: Union[int, str] = 0,
        rng: Optional[np.random.RandomState] = None,
    ):
        """Create the layer: Xavier-uniform weights, zero biases."""
        self.in_channels = int(in_channels)
        self.out_channels = int(out_channels)
        self.kernel_size = _as_pair(kernel_size, "kernel_size")
        self.stride = _as_pair(stride, "stride")
        self.padding = padding

        rng = rng if rng is not None else np.random.RandomState()
        kH, kW = self.kernel_size
        fan_in = self.in_channels * kH * kW
        fan_out = self.out_channels * kH * kW
        limit = np.sqrt(6.0 / (fan_in + fan_out))
        # kernel weights of shape (out_channels, in_channels, kH, kW)
        self.weight = rng.uniform(
            -limit, limit, (self.out_channels, self.in_channels, kH, kW)
        )
        self.bias = np.zeros(self.out_channels)
        # aliases used by the course evaluator
        self.weight_ = self.weight
        self.bias_ = self.bias

        self._weight_grad: Optional[np.ndarray] = None
        self._bias_grad: Optional[np.ndarray] = None
        self._prev_input: Optional[np.ndarray] = None
        self._weight_velocity: Optional[np.ndarray] = None
        self._bias_velocity: Optional[np.ndarray] = None

    def _pad_amounts(self) -> Tuple[Tuple[int, int], Tuple[int, int]]:
        """Resolve the padding setting to ((top, bottom), (left, right))."""
        kH, kW = self.kernel_size
        if isinstance(self.padding, str):
            mode = self.padding.lower()
            if mode == "valid":
                return (0, 0), (0, 0)
            if mode == "same":
                return (
                    ((kH - 1) // 2, kH - 1 - (kH - 1) // 2),
                    ((kW - 1) // 2, kW - 1 - (kW - 1) // 2),
                )
            raise ValueError(f"unknown padding mode {self.padding!r}")
        p = int(self.padding)
        return (p, p), (p, p)

    def _pad(self, X: np.ndarray, padding=None) -> np.ndarray:
        """Apply this layer's padding (or an explicit override) to X."""
        if padding is None:
            padding = self._pad_amounts()
        return pad_images(X, padding)

    def __call__(self, X: np.ndarray) -> np.ndarray:
        """Forward pass: convolution + bias.

        Args:
            X: ndarray of shape (batch_size, height, width, in_channels)

        Returns:
            ndarray of shape (batch_size, out_height, out_width, out_channels)
        """
        if X.ndim != 4:
            raise ValueError(f"expected (B, H, W, C) input, got shape {X.shape}")
        if X.shape[-1] != self.in_channels:
            raise ValueError(
                f"expected {self.in_channels} input channels, got {X.shape[-1]}"
            )
        self._prev_input = X
        Xp = self._pad(X)
        patches = get_patches(Xp, self.kernel_size, self.stride)
        return np.einsum("bxyihw,oihw->bxyo", patches, self.weight) + self.bias

    def backward(
        self, grad_output: np.ndarray, alpha: Optional[float] = None
    ) -> np.ndarray:
        """Compute gradients w.r.t. input, weights, and biases.

        ``alpha`` adds an L2 penalty gradient (``alpha * weight``) to the
        weight gradient.
        """
        if self._prev_input is None:
            raise RuntimeError("run the forward pass before calling backward()")
        kH, kW = self.kernel_size
        Xp = self._pad(self._prev_input)
        Hp, Wp = Xp.shape[1], Xp.shape[2]

        # a strided convolution's gradient equals a stride-1 gradient with
        # zeros between the positions the kernel actually visited
        grad = _dilate(grad_output, self.stride)
        Hd, Wd = grad.shape[1], grad.shape[2]

        # dJ/dW = input (x) delta
        input_patches = get_patches(Xp, self.kernel_size)[:, :Hd, :Wd]
        self._weight_grad = np.einsum("bxyihw,bxyo->oihw", input_patches, grad)
        if alpha:
            self._weight_grad = self._weight_grad + alpha * self.weight
        self._bias_grad = np.sum(grad_output, axis=(0, 1, 2))

        # dJ/dX = full convolution of delta with the 180°-rotated kernel
        grad_full = pad_images(grad, ((kH - 1, kH - 1), (kW - 1, kW - 1)))
        grad_patches = get_patches(grad_full, self.kernel_size)
        flipped = np.flip(self.weight, axis=(-2, -1))
        grad_input = np.einsum("bxyohw,oihw->bxyi", grad_patches, flipped)

        # positions the kernel never reached (input size not divisible by the
        # stride) receive zero gradient
        residual_h = Hp - grad_input.shape[1]
        residual_w = Wp - grad_input.shape[2]
        if residual_h or residual_w:
            grad_input = pad_images(grad_input, ((0, residual_h), (0, residual_w)))

        # crop off the forward padding
        (top, bottom), (left, right) = self._pad_amounts()
        grad_input = grad_input[:, top : Hp - bottom, left : Wp - right, :]
        return grad_input

    def update(self, learning_rate: float, momentum: float = 0.0) -> None:
        """Update weights and biases (gradient descent, optionally with momentum)."""
        if self._weight_grad is None:
            raise RuntimeError("call backward() before update()")
        if momentum:
            if self._weight_velocity is None:
                self._weight_velocity = np.zeros_like(self.weight)
                self._bias_velocity = np.zeros_like(self.bias)
            self._weight_velocity = (
                momentum * self._weight_velocity - learning_rate * self._weight_grad
            )
            self._bias_velocity = (
                momentum * self._bias_velocity - learning_rate * self._bias_grad
            )
            self.weight += self._weight_velocity
            self.bias += self._bias_velocity
        else:
            self.weight -= learning_rate * self._weight_grad
            self.bias -= learning_rate * self._bias_grad

    def get_output_shape(self, input_shape: Tuple[int, int, int]) -> Tuple[int, int, int]:
        """Output (height, width, channels) for an input (height, width, channels)."""
        h, w = input_shape[0], input_shape[1]
        (top, bottom), (left, right) = self._pad_amounts()
        kH, kW = self.kernel_size
        sH, sW = self.stride
        out_h = (h + top + bottom - kH) // sH + 1
        out_w = (w + left + right - kW) // sW + 1
        return (out_h, out_w, self.out_channels)

    def __repr__(self) -> str:
        """Readable description of the layer configuration."""
        return (
            f"ConvLayer({self.in_channels}, {self.out_channels}, "
            f"kernel_size={self.kernel_size}, stride={self.stride}, "
            f"padding={self.padding!r})"
        )


