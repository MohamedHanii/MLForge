# Generated By LLM _as_pair, get_patches, pad_images, _dilate
def _as_pair(value: SizeLike, name: str) -> Tuple[int, int]:
    """Normalize an int or (h, w) sequence to a tuple of two positive ints."""
    if isinstance(value, (int, np.integer)):
        pair = (int(value), int(value))
    else:
        pair = (int(value[0]), int(value[1]))
    if pair[0] <= 0 or pair[1] <= 0:
        raise ValueError(f"{name} must be positive, got {value}")
    return pair


def get_patches(
    arr: np.ndarray,
    patch_shape: Tuple[int, int],
    strides: Tuple[int, int] = (1, 1),
) -> np.ndarray:
    """Extract sliding-window patches from a batch of images.

    Parameters
    ----------
    arr : ndarray of shape (batch_size, height, width, channels)
    patch_shape : (patch_h, patch_w)
    strides : (stride_h, stride_w)

    Returns
    -------
    ndarray of shape (batch_size, out_h, out_w, channels, patch_h, patch_w)
        A read-only view (no copy) of every patch position.
    """
    if arr.ndim != 4:
        raise ValueError(f"expected a 4D (B, H, W, C) array, got shape {arr.shape}")
    patches = np.lib.stride_tricks.sliding_window_view(arr, patch_shape, axis=(1, 2))
    return patches[:, :: strides[0], :: strides[1]]


def pad_images(X: np.ndarray, padding) -> np.ndarray:
    """Zero-pad the spatial dimensions of a batch of images.

    Parameters
    ----------
    X : ndarray of shape (batch_size, height, width, channels)
    padding : int, or ((top, bottom), (left, right))
        Pixels to add on each spatial side.

    Returns
    -------
    Padded ndarray of shape (batch_size, height + pads, width + pads, channels)
    """
    if isinstance(padding, (int, np.integer)):
        pad_h = pad_w = (int(padding), int(padding))
    else:
        pad_h, pad_w = tuple(padding[0]), tuple(padding[1])
    if pad_h == (0, 0) and pad_w == (0, 0):
        return X
    return np.pad(X, ((0, 0), pad_h, pad_w, (0, 0)))


def _dilate(grad: np.ndarray, stride: Tuple[int, int]) -> np.ndarray:
    """Insert stride-1 zeros between spatial positions of a gradient map.

    Turns the gradient of a strided convolution into an equivalent stride-1
    gradient so the standard backprop formulas apply.
    """
    if stride == (1, 1):
        return grad
    b, h, w, c = grad.shape
    dilated = np.zeros(
        (b, (h - 1) * stride[0] + 1, (w - 1) * stride[1] + 1, c), dtype=grad.dtype
    )
    dilated[:, :: stride[0], :: stride[1]] = grad
    return dilated


